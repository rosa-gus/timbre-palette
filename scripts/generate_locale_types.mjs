import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import ts from "typescript";
import { supportedLocales, fallbackLocale, localeDefinitions } from "../shared/i18n/locales.mjs";
import { analyzeMessage } from "../shared/i18n/messages.mjs";
import { execFile } from "node:child_process";
import { promisify } from "node:util";

const compareKeys = (a, b) => {
  const first = a.match(/\d+|\D+/g) ?? [];
  const second = b.match(/\d+|\D+/g) ?? [];
  for (let index = 0; index < Math.min(first.length, second.length); index++) {
    const x = first[index], y = second[index];
    const order = /^\d+$/.test(x) && /^\d+$/.test(y)
      ? Number(x) - Number(y) : x < y ? -1 : x > y ? 1 : 0;
    if (order) return order;
  }
  return first.length - second.length || (a < b ? -1 : a > b ? 1 : 0);
};

function parseCatalog(source, filename) {
  const catalog = JSON.parse(source);
  if (!catalog || typeof catalog !== "object" || Array.isArray(catalog)) {
    throw new Error(`${filename}: expected an object of message strings`);
  }
  function checkDuplicates(node, prefix = "") {
    if (!ts.isObjectLiteralExpression(node)) return;
    const keys = new Set();
    for (const property of node.properties) {
      const key = property.name.text;
      const path = prefix ? `${prefix}.${key}` : key;
      if (keys.has(key)) throw new Error(`${filename}: duplicate key ${path}`);
      keys.add(key);
      checkDuplicates(property.initializer, path);
    }
  }
  checkDuplicates(ts.parseJsonText(filename, source).statements[0].expression);
  return catalog;
}

export function flattenCatalog(catalog, filename = "locale.json") {
  const messages = Object.create(null);
  function visit(branch, prefix = "") {
    if (!branch || typeof branch !== "object" || Array.isArray(branch) || !Object.keys(branch).length) {
      throw new Error(`${filename}: ${prefix || "catalog"} must be a non-empty message group`);
    }
    for (const [key, value] of Object.entries(branch)) {
      if (!key || key.includes(".")) throw new Error(`${filename}: use nested objects for ${key || "(empty key)"}`);
      const path = prefix ? `${prefix}.${key}` : key;
      if (typeof value === "string") messages[path] = value;
      else visit(value, path);
    }
  }
  visit(catalog);
  return messages;
}

/** Each namespace has one owner file; merging must never overwrite messages. */
export function mergeCatalogs(files) {
  const catalog = Object.create(null);
  for (const { filename, source } of files) {
    const part = parseCatalog(source, filename);
    flattenCatalog(part, filename);
    for (const [namespace, messages] of Object.entries(part)) {
      if (Object.hasOwn(catalog, namespace)) throw new Error(`${filename}: conflicting namespace ${namespace}`);
      catalog[namespace] = messages;
    }
  }
  return catalog;
}

function messageContract(value, key) {
  if (!value.trim()) throw new Error(`Empty message in ${key}`);
  let contract;
  try { contract = analyzeMessage(value); }
  catch (error) { throw new Error(`${key}: ${error.message}`); }
  const wrappers = (text) => [...text.matchAll(/<([a-z]+)>/g)].map((match) => match[1]).filter((name) => name !== "upper").sort().join(",");
  for (const variant of contract.variants) {
    if (!variant.trim()) throw new Error(`Empty plural form in ${key}`);
    const plain = variant.replace(/<(upper|emphasis|line|value|version)>([^<>]*)<\/\1>/gs, "$2");
    if (/[<>]/.test(plain)) throw new Error(`Invalid or nested message wrapper in ${key}`);
    if (wrappers(variant) !== wrappers(contract.variants[0])) throw new Error(`Message wrappers differ between plural forms in ${key}`);
  }
  return { parameters: contract.parameters, plurals: contract.plurals, wrappers: wrappers(contract.variants[0]) };
}

function renderParameters(catalog) {
  const entries = Object.entries(flattenCatalog(catalog)).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
  const contracts = entries.map(([key, value]) => [key, messageContract(value, key)]);
  const type = (name, field, entries = contracts) => `export type ${name} = {\n` + entries.map(([key, contract]) =>
    `  ${JSON.stringify(key)}: ${contract[field].map((parameter) => JSON.stringify(parameter)).join(" | ") || "never"};`).join("\n") + "\n};\n";
  return "// Generated by scripts/generate_locale_types.mjs. Do not edit.\n" +
    type("MessageParameters", "parameters") + type("PluralMessages", "plurals", contracts.filter(([, contract]) => contract.plurals.length)) +
    "export type PluralParameters = { [Key in keyof MessageParameters]: Key extends keyof PluralMessages ? PluralMessages[Key] : never };\n";
}

/** Generate parameter types only; JSON remains the sole source of message text. */
export function renderMessageTypes(source, filename = "locale.json") {
  return renderParameters(parseCatalog(source, filename));
}

export function validateTranslation(base, translation) {
  renderParameters(base);
  renderParameters(translation);
  const source = flattenCatalog(base), target = flattenCatalog(translation);
  for (const [key, text] of Object.entries(target)) {
    if (!Object.hasOwn(source, key)) throw new Error(`Unknown translation key: ${key}`);
    if (JSON.stringify(messageContract(source[key], key)) !== JSON.stringify(messageContract(text, key)))
      throw new Error(`Message parameters or wrappers differ in ${key}`);
  }
}

function orderedCatalog(catalog) {
  return Object.fromEntries(Object.keys(catalog).sort(compareKeys).map((key) => [
    key, typeof catalog[key] === "string" ? catalog[key] : orderedCatalog(catalog[key]),
  ]));
}

async function update(output, generated, app, check) {
  const current = await readFile(output, "utf8").catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  if (current === generated) return;
  if (check) throw new Error(`${app}: stale locale artifacts; run yarn locales:generate`);
  await writeFile(output, generated);
}

/** Fallback messages never contribute to a locale's own coverage. */
export function messageCoverage(base, translation) {
  const expected = Object.keys(flattenCatalog(base));
  const actual = translation ? flattenCatalog(translation) : {};
  return { translated: expected.filter((key) => typeof actual[key] === "string" && actual[key].trim()).length, total: expected.length };
}

export function renderCoverageTable(catalogs, editorial) {
  const locales = [...new Set([...Object.keys(catalogs.web), ...Object.keys(catalogs.editorial), ...Object.keys(editorial)])].sort();
  const cell = (counts) => {
    if (!counts) return "—";
    const { translated, total } = counts;
    // Truncate so incomplete coverage never rounds up to 100%.
    return `${total ? `${Math.floor(translated * 1000 / total) / 10}%` : "—"} (${translated}/${total})`;
  };
  const lines = locales.map((locale) => `| ${locale} | ${cell(catalogs.web[locale] && messageCoverage(catalogs.web[fallbackLocale], catalogs.web[locale]))} | ${cell(catalogs.editorial[locale] && messageCoverage(catalogs.editorial[fallbackLocale], catalogs.editorial[locale]))} | ${cell(editorial[locale])} |`);
  return ["| Locale | Web UI | Editorial UI | Reviewed editorial content |", "| --- | ---: | ---: | ---: |", ...lines].join("\n");
}

export async function updateCoverage(output, table, check) {
  const source = await readFile(output, "utf8");
  const start = "<!-- translation-coverage:start -->", end = "<!-- translation-coverage:end -->";
  if (source.split(start).length !== 2 || source.split(end).length !== 2 || source.indexOf(start) > source.indexOf(end))
    throw new Error("Translation policy must contain one ordered pair of coverage markers");
  const generated = source.slice(0, source.indexOf(start) + start.length) + "\n\n" + table + "\n\n" + source.slice(source.indexOf(end));
  await update(output, generated, "Translation coverage", check);
}

export function validateLocaleDirectories(names, app) {
  const missing = supportedLocales.filter((tag) => !names.includes(tag));
  const unknown = names.filter((tag) => !supportedLocales.includes(tag));
  if (missing.length || unknown.length)
    throw new Error(`${app}: locale directories differ from shared/i18n/locales.json (missing: ${missing.join(", ") || "none"}; unregistered: ${unknown.join(", ") || "none"})`);
}

async function main(args) {
  const check = args.includes("--check");
  const format = args.includes("--format");
  const selected = args.filter((arg) => !["--check", "--format"].includes(arg));
  const apps = selected.length ? selected : ["web", "editorial"];
  if ((check && format) || apps.some((app) => !["web", "editorial"].includes(app))) {
    throw new Error("Usage: node scripts/generate_locale_types.mjs [--check|--format] [web|editorial]");
  }
  const catalogs = { web: {}, editorial: {} };
  for (const app of Object.keys(catalogs)) {
    const directory = new URL(`../${app}/src/i18n/`, import.meta.url);
    const directories = (await readdir(new URL("locales/", directory), { withFileTypes: true }))
      .filter((entry) => entry.isDirectory()).map((entry) => entry.name);
    validateLocaleDirectories(directories, app);
    const namespaceFiles = {};
    let sourceCatalog;
    for (const locale of [fallbackLocale, ...supportedLocales.filter((tag) => tag !== fallbackLocale)]) {
      const input = new URL(`locales/${locale}/`, directory);
      const filenames = (await readdir(input)).filter((name) => name.endsWith(".json")).sort();
      if (!filenames.length) throw new Error(`${app}/${locale}: no locale files found`);
      const files = await Promise.all(filenames.map(async (filename) => ({
        filename, source: await readFile(new URL(filename, input), "utf8"),
      })));
      const catalog = mergeCatalogs(files);
      catalogs[app][locale] = catalog;
      namespaceFiles[locale] = Object.fromEntries(files.flatMap((file) =>
        Object.keys(JSON.parse(file.source)).map((namespace) => [namespace, file.filename])));
      const parameters = renderParameters(catalog);
      if (locale === fallbackLocale) sourceCatalog = catalog;
      else validateTranslation(sourceCatalog, catalog);
      if (!apps.includes(app)) continue;
      for (const file of files) {
        const ordered = JSON.stringify(orderedCatalog(parseCatalog(file.source, file.filename)), null, 2) + "\n";
        if (ordered !== file.source) {
          if (format) await writeFile(new URL(file.filename, input), ordered);
          else throw new Error(`${app}/${locale}/${file.filename}: unordered catalog; run yarn locales:format`);
        }
      }
      const imports = filenames.map((filename, index) =>
        `import part${index} from ${JSON.stringify(`./locales/${locale}/${filename}`)};`);
      const loader = "// Generated by scripts/generate_locale_types.mjs. Do not edit.\n" +
        imports.join("\n") + "\n\nexport default { " + filenames.map((_, index) => `...part${index}`).join(", ") + " };\n";
      if (locale === fallbackLocale) await update(new URL("message-parameters.generated.d.ts", directory), parameters, app, check);
      await update(new URL(localeDefinitions[locale].catalog, directory), loader, app, check);
    }
    if (apps.includes(app)) {
      const generated = "// Generated by scripts/generate_locale_types.mjs. Do not edit.\n";
      const fallbackFile = localeDefinitions[fallbackLocale].catalog.replace(/\.ts$/, "");
      const loaders = generated + `import defaultMessages from "./${fallbackFile}";\nexport { defaultMessages };\n` +
        "export const catalogLoaders = {\n" + supportedLocales.map((tag) =>
          `  ${JSON.stringify(tag)}: ${tag === fallbackLocale ? "async () => defaultMessages" : `() => import("./${localeDefinitions[tag].catalog.replace(/\.ts$/, "")}").then((module) => module.default)`},`).join("\n") + "\n};\n";
      await update(new URL("catalog-loaders.generated.ts", directory), loaders, app, check);
      if (app === "web") {
        const imports = [], groups = [];
        for (const [group, namespace] of [["formatting", "formatting"], ["narratives", "narrative"]]) {
          const entries = [];
          for (const [index, tag] of supportedLocales.entries()) {
            const name = `${group}${index}`;
            if (Object.hasOwn(catalogs.web[tag], namespace)) {
              imports.push(`import ${name} from ${JSON.stringify(`./locales/${tag}/${namespaceFiles[tag][namespace]}`)};`);
              entries.push(`  ${JSON.stringify(tag)}: ${name},`);
            } else entries.push(`  ${JSON.stringify(tag)}: {},`);
          }
          groups.push(`export const ${group}Catalogs = {\n${entries.join("\n")}\n};`);
        }
        await update(new URL("presentation-catalogs.generated.ts", directory), generated + imports.join("\n") + "\n\n" + groups.join("\n") + "\n", app, check);
      }
    }
  }
  const root = fileURLToPath(new URL("../", import.meta.url));
  const { stdout } = await promisify(execFile)("python3", ["-m", "scripts.translation_coverage"], { cwd: root });
  await updateCoverage(new URL("../docs/translation-policy.md", import.meta.url), renderCoverageTable(catalogs, JSON.parse(stdout)), check);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
