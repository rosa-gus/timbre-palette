import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import ts from "typescript";

const compareKeys = (a, b) => {
  const first = a.match(/\d+|\D+/g) ?? [];
  const second = b.match(/\d+|\D+/g) ?? [];
  for (let index = 0; index < Math.min(first.length, second.length); index++) {
    const x = first[index], y = second[index];
    const order = /^\d+$/.test(x) && /^\d+$/.test(y)
      ? Number(x) - Number(y) : x < y ? -1 : x > y ? 1 : 0;
    if (order) return order;
  }
  return first.length - second.length || (a < b ? -1 : a > b ? 1 : 0);
};

function parseCatalog(source, filename) {
  const catalog = JSON.parse(source);
  if (!catalog || typeof catalog !== "object" || Array.isArray(catalog)) {
    throw new Error(`${filename}: expected an object of message strings`);
  }
  function checkDuplicates(node, prefix = "") {
    if (!ts.isObjectLiteralExpression(node)) return;
    const keys = new Set();
    for (const property of node.properties) {
      const key = property.name.text;
      const path = prefix ? `${prefix}.${key}` : key;
      if (keys.has(key)) throw new Error(`${filename}: duplicate key ${path}`);
      keys.add(key);
      checkDuplicates(property.initializer, path);
    }
  }
  checkDuplicates(ts.parseJsonText(filename, source).statements[0].expression);
  return catalog;
}

export function flattenCatalog(catalog, filename = "locale.json") {
  const messages = Object.create(null);
  function visit(branch, prefix = "") {
    if (!branch || typeof branch !== "object" || Array.isArray(branch) || !Object.keys(branch).length) {
      throw new Error(`${filename}: ${prefix || "catalog"} must be a non-empty message group`);
    }
    for (const [key, value] of Object.entries(branch)) {
      if (!key || key.includes(".")) throw new Error(`${filename}: use nested objects for ${key || "(empty key)"}`);
      const path = prefix ? `${prefix}.${key}` : key;
      if (typeof value === "string") messages[path] = value;
      else visit(value, path);
    }
  }
  visit(catalog);
  return messages;
}

/** Each namespace has one owner file; merging must never overwrite messages. */
export function mergeCatalogs(files) {
  const catalog = Object.create(null);
  for (const { filename, source } of files) {
    const part = parseCatalog(source, filename);
    flattenCatalog(part, filename);
    for (const [namespace, messages] of Object.entries(part)) {
      if (Object.hasOwn(catalog, namespace)) throw new Error(`${filename}: conflicting namespace ${namespace}`);
      catalog[namespace] = messages;
    }
  }
  return catalog;
}

function renderParameters(catalog) {
  const entries = Object.entries(flattenCatalog(catalog)).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
  const lines = entries.map(([key, value]) => {
    const withoutWrappers = value.replace(/<(upper|emphasis|line|value|version)>([^<>]*)<\/\1>/gs, "$2");
    if (/<\/?[A-Za-z][^>]*>/.test(withoutWrappers)) {
      throw new Error(`Invalid or nested message wrapper in ${key}`);
    }
    const parameters = [...new Set([...value.matchAll(/\{([^{}]+)\}/g)].map((match) => match[1]))].sort();
    if (parameters.some((name) => !/^[A-Za-z][A-Za-z0-9_]*$/.test(name)) ||
        /[{}]/.test(value.replace(/\{([^{}]+)\}/g, ""))) {
      throw new Error(`Malformed parameter in ${key}`);
    }
    return `  ${JSON.stringify(key)}: ${parameters.map((name) => JSON.stringify(name)).join(" | ") || "never"};`;
  });
  return "// Generated by scripts/generate_locale_types.mjs. Do not edit.\n" +
    "export type MessageParameters = {\n" + lines.join("\n") + "\n};\n";
}

/** Generate parameter types only; JSON remains the sole source of message text. */
export function renderMessageTypes(source, filename = "locale.json") {
  return renderParameters(parseCatalog(source, filename));
}

function orderedCatalog(catalog) {
  return Object.fromEntries(Object.keys(catalog).sort(compareKeys).map((key) => [
    key, typeof catalog[key] === "string" ? catalog[key] : orderedCatalog(catalog[key]),
  ]));
}

async function update(output, generated, app, check) {
  const current = await readFile(output, "utf8").catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  if (current === generated) return;
  if (check) throw new Error(`${app}: stale locale artifacts; run yarn locales:generate`);
  await writeFile(output, generated);
}

async function main(args) {
  const check = args.includes("--check");
  const format = args.includes("--format");
  const selected = args.filter((arg) => !["--check", "--format"].includes(arg));
  const apps = selected.length ? selected : ["web", "editorial"];
  if ((check && format) || apps.some((app) => !["web", "editorial"].includes(app))) {
    throw new Error("Usage: node scripts/generate_locale_types.mjs [--check|--format] [web|editorial]");
  }
  for (const app of apps) {
    const directory = new URL(`../${app}/src/i18n/`, import.meta.url);
    const input = new URL("locales/pt-BR/", directory);
    const filenames = (await readdir(input)).filter((name) => name.endsWith(".json")).sort();
    if (!filenames.length) throw new Error(`${app}: no locale files found`);
    const files = await Promise.all(filenames.map(async (filename) => ({
      filename, source: await readFile(new URL(filename, input), "utf8"),
    })));
    const catalog = mergeCatalogs(files);
    const parameters = renderParameters(catalog);
    for (const file of files) {
      const ordered = JSON.stringify(orderedCatalog(parseCatalog(file.source, file.filename)), null, 2) + "\n";
      if (ordered !== file.source) {
        if (format) await writeFile(new URL(file.filename, input), ordered);
        else throw new Error(`${app}/${file.filename}: unordered catalog; run yarn locales:format`);
      }
    }
    const imports = filenames.map((filename, index) =>
      `import part${index} from ${JSON.stringify(`./locales/pt-BR/${filename}`)};`);
    const loader = "// Generated by scripts/generate_locale_types.mjs. Do not edit.\n" +
      imports.join("\n") + "\n\nexport default { " + filenames.map((_, index) => `...part${index}`).join(", ") + " };\n";
    await update(new URL("message-parameters.generated.d.ts", directory), parameters, app, check);
    await update(new URL("catalog.generated.ts", directory), loader, app, check);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
